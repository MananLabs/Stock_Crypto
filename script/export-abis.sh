#!/usr/bin/env bash
# Exports ABIs from Foundry artifacts to abis/*.json and abis/index.ts (viem-ready, `as const`).
set -euo pipefail
cd "$(dirname "$0")/.."
forge build --silent
{
  echo "// Generated by script/export-abis.sh — do not edit."
  for c in BharatEquityToken BharatEquityTokenFactory BharatEquityMarketplace; do
    jq '.abi' "out/$c.sol/$c.json" > "abis/$c.json"
    echo "export const ${c}Abi = $(jq -c '.abi' "out/$c.sol/$c.json") as const;"
  done
} > abis/index.ts
echo "ABIs written to abis/"
