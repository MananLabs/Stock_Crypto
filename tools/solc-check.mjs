// Compile-checks contracts/, test/ and script/ with solc-js when Foundry is unavailable.
// Usage: node tools/solc-check.mjs [--abi] [dir...]   (--abi writes abis/*.json + abis/index.ts)
import solc from "solc";
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const writeAbi = args.includes("--abi");
const dirs = args.filter((a) => a !== "--abi").length ? args.filter((a) => a !== "--abi") : ["contracts"];
const files = dirs.flatMap((d) => fs.readdirSync(d, { recursive: true }).filter((f) => f.endsWith(".sol")).map((f) => path.join(d, f)));
const remap = [["@openzeppelin/contracts/", "node_modules/@openzeppelin/contracts/"], ["forge-std/", "lib/forge-std/src/"]];
const resolve = (p) => { for (const [a, b] of remap) if (p.startsWith(a)) return b + p.slice(a.length); return p; };
const input = {
  language: "Solidity",
  sources: Object.fromEntries(files.map((f) => [f, { content: fs.readFileSync(f, "utf8") }])),
  settings: { evmVersion: "cancun", optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: (p) => { try { return { contents: fs.readFileSync(resolve(p), "utf8") }; } catch { return { error: "not found: " + p }; } } }));
const errs = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) if (e.severity === "error" || !/SPDX|unreachable/.test(e.message)) console.log(e.formattedMessage);
if (errs.length) process.exit(1);
for (const f of files.filter((f) => f.startsWith("contracts")))
  for (const [name, c] of Object.entries(out.contracts[f] ?? {})) console.log(`${name}: ${c.evm.bytecode.object.length / 2} bytes`);
if (writeAbi) {
  const lines = ["// Generated by script/export-abis.sh — do not edit."];
  for (const c of ["BharatEquityToken", "BharatEquityTokenFactory", "BharatEquityMarketplace"]) {
    const abi = out.contracts[`contracts/${c}.sol`][c].abi;
    fs.writeFileSync(`abis/${c}.json`, JSON.stringify(abi, null, 2) + "\n");
    lines.push(`export const ${c}Abi = ${JSON.stringify(abi)} as const;`);
  }
  fs.writeFileSync("abis/index.ts", lines.join("\n") + "\n");
  console.log("ABIs written to abis/");
}
console.log(`ok (${files.length} files, solc ${solc.version()})`);
